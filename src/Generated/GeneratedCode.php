namespace LucianoPereira\Crucible\Generated;

use Closure;
use ParseError;

use function count;
use function explode;
use function file_put_contents;
use function implode;
use function md5;
use function sprintf;
use function str_pad;
use function strlen;

use const STR_PAD_LEFT;

/**
 * The one place Crucible compiles code it wrote itself.
 *
 * Five generators need PHP to declare something at runtime — doubles,
 * the mockery surface, trait composition, snapshot identity, and a
 * doctest expression — and each used to call eval() for itself. That is
 * five copies of the one boundary where a gate stops being able to see
 * anything: PHPStan cannot read inside a string literal, phpcpd finds
 * no clone there (D-108), and the mutation runner drops eval()'d
 * pseudo-paths (`MutationCommand.php:334`).
 *
 * Holding it in one function is what makes "exactly one eval() exists"
 * a checkable claim rather than a grep — ApprovedEvalRule's allowlist
 * is this file alone — and gives every generator the same diagnosis
 * instead of the bare ParseError four of them had.
 *
 * Only a ParseError is caught. A Throwable raised by generated code
 * while it RUNS belongs to whoever wrote the expression — a doctest
 * that divides by zero is not a generation failure — and passes
 * through untouched. Compile errors that are not parse errors (an
 * invalid constant expression, a trait collision) cannot be caught by
 * anyone: they are refused before reaching here, which is why the
 * callers guard.
 */
final class GeneratedCode
{
    /** @var ?non-empty-string */
    private static ?string $recordTo = null;

    /**
     * Compile generated source, naming what it was for when it fails.
     *
     * @param non-empty-string $source
     * @param non-empty-string $describing what the source was generated for, in the reader's terms
     */
    public static function evaluate(string $source, string $describing): mixed
    {
        self::record($source, $describing);

        try {
            return eval($source);
        } catch (ParseError $broken) {
            throw new GeneratedCodeException(
                sprintf(
                    "Crucible generated source for %s that PHP cannot parse: %s\n\n%s",
                    $describing,
                    $broken->getMessage(),
                    self::numbered($source),
                ),
                $broken->getCode(),
                $broken,
            );
        }
    }

    /**
     * Record every source generated by $work into $directory, and stop
     * when it returns — however it returns.
     *
     * This is what a type checker needs and cannot otherwise have. A
     * string is invisible to PHPStan; the same string in a file is not,
     * and `composer analyse:generated` points a level-max run at the
     * result. The hook lives here because the boundary does: one place
     * to record, rather than five generators each having to remember.
     *
     * Scoped rather than a pair of calls, and the switch is private for
     * that reason. The hook is process-global, so a generator throwing
     * midway through a corpus used to leave it on: the next thing to
     * generate anything wrote into a directory nobody meant, and in a
     * test run that is a directory already deleted. `finally` makes
     * that impossible instead of unlikely — the same trade as
     * DoubleState holding its own double, where the point was never the
     * microseconds.
     *
     * @param non-empty-string $directory
     * @param Closure(): void  $work
     */
    public static function recording(string $directory, Closure $work): void
    {
        $previous = self::$recordTo;

        self::$recordTo = $directory;

        try {
            $work();
        } finally {
            self::$recordTo = $previous;
        }
    }

    private static function record(string $source, string $describing): void
    {
        $directory = self::$recordTo;

        if ($directory === null) {
            return;
        }

        // Named by content, so exercising the same shape twice writes
        // one file and the directory is a set of DISTINCT generated
        // shapes rather than a log of calls.
        file_put_contents(
            $directory . '/' . md5($source) . '.php',
            "<?php\n\n/* Generated by Crucible for " . $describing . ". Written by GeneratedCode::recording(). */\n\n" . $source . "\n",
        );
    }

    /**
     * The source with line numbers, because the parse error's own line
     * number refers to text that exists nowhere a reader can look.
     */
    private static function numbered(string $source): string
    {
        $lines  = explode("\n", $source);
        $width  = strlen((string) count($lines));
        $shown  = [];
        $number = 0;

        foreach ($lines as $line) {
            $number++;
            $shown[] = str_pad((string) $number, $width, ' ', STR_PAD_LEFT) . ' | ' . $line;
        }

        return implode("\n", $shown);
    }
}
